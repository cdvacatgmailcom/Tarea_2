package uni1a;

// Subclase Pelicula que extiende de ContenidoAudiovisual
public class Pelicula extends ContenidoAudiovisual {
    private String estudio;
    private Actor actor;
    
    public Pelicula(String titulo, int duracionEnMinutos, String genero, String estudio, String actor){
        super(titulo, duracionEnMinutos, genero);
        this.estudio = estudio;
        this.actor = new Actor(actor);
    }

    public String getEstudio() {
        return estudio;
    }

    public void setEstudio(String estudio) {
        this.estudio = estudio;
    }
    
    @Override
    public void mostrarDetalles() {
        System.out.println("Detalles de la Película:");
        System.out.println("ID: " + getId());
        System.out.println("Título: " + getTitulo());
        System.out.println("Duración en minutos: " + getDuracionEnMinutos());
        System.out.println("Género: " + getGenero());
        System.out.println("Estudio: " + getEstudio());
        System.out.println("Actor: " + actor.getNombreActor());
        System.out.println();
    }
}